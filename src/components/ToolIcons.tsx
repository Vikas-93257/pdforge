export function ToolIcon({
  name,
  size = 24,
  ...props
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const Icon = TOOL_ICONS[name] ?? FileText;
  return <Icon size={size} strokeWidth={1.7} aria-hidden="true" {...props} />;
}
